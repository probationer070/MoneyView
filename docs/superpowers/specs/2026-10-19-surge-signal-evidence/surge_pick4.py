"""Event list of the chosen surge setting: n10 k3 Z2.0 P5 B60 R60, persistence dropped, 4 of 4, gate cap20.
Research only. Run from the bt2 folder next to surge.py/backtest.py:  python surge_pick4.py [out.md]
"""
import sys

import numpy as np

import surge as sg

S = dict(n=10, k=3, Z=2.0, P=5, U=3, B=60, R=60, M=4)  # U unused: persistence is dropped


def end_reason(ind, a, b, n, last):
    if b == last and not (ind["v"][b] < ind["ema"][n][b]):
        # open or ended by quiet on the final bar; cannot tell an open event from a quiet end
        hi = ind["newhigh"]
        return "open" if hi[max(a, b - sg.QUIET + 1):b + 1].any() else "quiet10"
    return "ema_break" if ind["v"][b] < ind["ema"][n][b] else "quiet10"


def main(out):
    ctx = sg.build()
    r = sg.run(ctx, S, drop="pers", M=4, keep_events=True)
    cal, last = ctx["cal"], len(ctx["cal"]) - 1
    ev = sorted(r["event_list"], key=lambda e: (e["start"], e["theme"]))
    for e in ev:
        e["reason"] = end_reason(ctx["ind"][e["theme"]], e["start_i"], e["end_i"], S["n"], last)
    g = "cap20"
    f = lambda x: "-" if x is None else f"{x * 100:+.1f}%"
    L = ["# Chosen surge setting: full event list", "",
         "Setting `n10 k3 Z2.0 P5 B60 R60`, persistence off, magnitude + acceleration + breadth + RSI (4 of 4), "
         "gate cap20. Events from %s to %s (%.2f years). Generated by `surge_pick4.py`." % (cal[ctx['i0']].date(), cal[-1].date(), ctx['years']),
         "", "| variant | events/yr | banner up | shown/yr | useful | false | fwd10 | recall |", "|---|---|---|---|---|---|---|---|",
         f"| without pers, 4 of 4 | {r['events_yr']:.1f} | {sg.sh(r['banner_'+g])} | {r['shown_'+g+'_yr']:.1f} | {sg.sh(r['useful_'+g])} | "
         f"{sg.sh(r['false_'+g])} | {sg.pct(r['fwd10_'+g])} | {r['recall_'+g]}/{r['rallies']} |", "",
         "end_reason: ema_break = close under EMA10; quiet10 = 10 trading days without a new 20d high; open = still running on the last bar. "
         "shown = the cap20 banner was up on the start day. fwd and run-up are from the start-day close.", "",
         "## Events", "", "| theme | start | end | end_reason | shown | fwd5 | fwd10 | fwd20 | max run-up 10d |", "|---|---|---|---|---|---|---|---|---|"]
    for e in ev:
        L.append(f"| {e['theme']} | {e['start']} | {e['end']} | {e['reason']} | {'yes' if e['shown_'+g] else 'no'} | "
                 f"{f(e['fwd5'])} | {f(e['fwd10'])} | {f(e['fwd20'])} | {f(e['runup10'])} |")
    L += ["", "## 2026 semis", "", "| series | start | end | end_reason | shown |", "|---|---|---|---|---|"]
    for e in ev:
        if e["start"] >= "2026-01-01" and (e["theme"] == "^SOX" or e["theme"] in sg.bt.SEMI):
            L.append(f"| {e['theme']} | {e['start']} | {e['end']} | {e['reason']} | {'yes' if e['shown_'+g] else 'no'} |")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(len(ev), "events;", {k: r[k] for k in ("events_yr", "banner_cap20", "shown_cap20_yr", "useful_cap20", "false_cap20", "fwd10_cap20", "recall_cap20", "rallies")})


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "report_surge_pick4.md")
